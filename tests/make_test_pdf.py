"""
動作確認用のダミーPDFを作る（白書の体裁だけを真似た架空の文書。内容・数値は作り物）。

再現している白書PDFの特徴:
  - 毎ページのヘッダー（文書名）とフッター（ページ番号）
  - 全角数字の見出し「第１部」「第２章」「第１節」
  - 行の途中で改行される日本語の文
  - 「【第○-○】」形式の図表番号
"""

import sys
from pathlib import Path

import pymupdf


HEADER = "テスト用ダミー文書（白書の体裁を模した架空の内容）"

PAGES = [
    ["第１部　エネルギーを巡る状況",
     "第１章　エネルギー価格の変動",
     "架空国Ａでは、２０２５年度に輸入燃料の価格が前年度比で約１５％上昇した。この上昇は主に海上輸送の混乱によるもので、"
     "電気料金とガソリン価格の双方に影響した。",
     "政府は価格高騰への対策として、燃料備蓄の一部放出と、家庭向け電気料金の負担軽減策を実施した。",
     "【第１１１－１】輸入燃料価格の推移（架空）"],
    ["第２章　省エネルギーの取組",
     "架空国Ａの最終エネルギー消費は、２０１０年度から２０２５年度までに約１２％減少した。とくに業務部門での照明の"
     "ＬＥＤ化と、建物の断熱性能の向上が寄与した。",
     "一方で運輸部門の削減は緩やかであり、電気自動車の普及拡大が今後の課題とされている。"],
    ["第２部　講じた施策の状況",
     "第３章　再生可能エネルギーの導入",
     "第１節　地熱発電",
     "地熱発電は天候に左右されずに安定して発電できる電源である。架空国Ａの地熱資源量は世界有数とされるが、"
     "導入量は資源量に比べて小さい。",
     "導入が進まない主な理由として、①開発の初期段階で掘削の成功率が低く費用がかさむこと、②有望な地域の多くが"
     "自然公園内にあること、③温泉事業者など地域との合意形成に時間がかかること、の三点が挙げられる。",
     "このため政府は、初期調査の費用を支援する制度と、地域との共生を図るための協議の場づくりを進めている。"],
    ["第２節　太陽光発電",
     "太陽光発電の導入量は２０２５年度末時点で累計約９０ＧＷに達した。晴れた春の休日の昼間には、太陽光の発電量が"
     "需要を上回る時間帯が生じ、出力制御が行われる日が増えている。",
     "余った電気を有効に使うため、蓄電池の導入支援と、昼間に電気を使うよう促す料金メニューの普及が進められている。",
     "【第２３２－１】太陽光発電の累計導入量（架空）"],
]


def main(out):
    doc = pymupdf.open()
    for i, paras in enumerate(PAGES, start=1):
        page = doc.new_page(width=595, height=842)
        kw = dict(fontname="japan")       # PyMuPDF内蔵の日本語フォント（埋め込まないので軽い）
        page.insert_text((60, 40), HEADER, fontsize=9, **kw)
        page.insert_text((290, 815), f"－{i}－", fontsize=9, **kw)
        page.insert_textbox(pymupdf.Rect(60, 70, 535, 790), "\n\n".join(paras),
                            fontsize=11, lineheight=1.6, **kw)
    out = Path(out)
    out.parent.mkdir(parents=True, exist_ok=True)
    doc.save(out, garbage=4, deflate=True)
    print("作成:", out)


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "data/pdf_test/test_whitepaper.pdf")
